//
// Encode up to PASSCODE_MAX characters of in into out.
// out is zero filled first; returns the number of encoded bytes.
// Values above 126 after the position offset wrap as wfview does:
// p = 32 + p % 127, which always stays inside the 159-entry table.
//

size_t passcode_encode(const char *in, uint8_t out[PASSCODE_MAX])
{
	size_t i;

	memset(out, 0, PASSCODE_MAX);

	if (in == NULL)
		return 0;

	for (i = 0; i < PASSCODE_MAX && in[i] != '\0'; i++) {
		int p = (int)(unsigned char)in[i] + (int)i;

		if (p > 126)
			p = 32 + p % 127;

		out[i] = C_SEQUENCE[p];
	}

	return i;
}
